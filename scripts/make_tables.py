"""Builds the table views of the repository from the manuscript's LaTeX tables and the maturity CSV.
Usage: python scripts/make_tables.py path/to/'section 2 - Data.tex' path/to/'section 1 - Introduction.tex'
Writes data/datasets.csv, data/survey_references.csv and tables/*.md."""
import re, os, sys, csv

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
data_tex, intro_tex = sys.argv[1], sys.argv[2]
BS = chr(92)


def clean(s):
    s = s.replace("{,}", ",").replace(BS + ",", " ").replace("~", " ").replace(BS + "&", "&")
    s = re.sub(r"\\textsuperscript\{[^}]*\}", "", s)
    s = re.sub(r"\\(?:emph|textit|textbf)\{([^}]*)\}", r"\1", s)
    s = s.replace("$>$", ">").replace("$<$", "<").replace("\\%", "%").replace("\\ ", " ").replace("\\quad", "").replace("$^\\ast$", "*")
    s = re.sub(r"\$([^$]*)\$", r"\1", s)
    s = re.sub(r"[{}]", "", s)
    return re.sub(r"\s+", " ", s).strip()


def cites(s):
    return [k.strip() for c in re.findall(r"\\cite\{([^}]*)\}", s) for k in c.split(",")]


t = open(data_tex, encoding="utf-8").read()
rows = []
for tab, label in (("datasets_overview_a", "Mainstream"), ("datasets_overview_b", "Specialised and emerging")):
    m = re.search(r"\\label\{tab:" + tab + r"\}(.*?)\\end\{tabular\}", t, re.S)
    pillar = cat = ""
    for line in m.group(1).split("\n"):
        line = line.strip()
        pm = re.search(r"--- (SENSE|PLAN|ACT) ---", line)
        if pm:
            pillar = pm.group(1).title(); continue
        cm = re.search(r"\\multicolumn\{5\}\{l\}\{\\textit\{([^}]*)\}\}", line)
        if cm:
            cat = clean(cm.group(1)); continue
        if line.startswith("\\quad") and "&" in line:
            cells = [c for c in line.rstrip("\\ ").split("&")]
            cells = re.split(r"(?<!\\)&", line.rstrip().rstrip("\\").rstrip())
            if len(cells) < 5:
                continue
            name = clean(re.sub(r"~?\\cite\{[^}]*\}", "", cells[0]))
            rows.append({"table": label, "pillar": pillar, "task": cat, "dataset": name, "year": clean(cells[1]),
                         "region": clean(cells[2]), "scale": clean(cells[3]), "note": clean(cells[4]),
                         "cite_keys": ";".join(cites(cells[0]))})

os.makedirs(os.path.join(root, "tables"), exist_ok=True)
with open(os.path.join(root, "data", "datasets.csv"), "w", encoding="utf-8", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)

# bibliography lookup for links
bib = {}
for fn in ("references.bib", "refs-spa.bib", "refs-plan.bib", "refs-act.bib"):
    p = os.path.join(root, "data", fn)
    if os.path.exists(p):
        for m in re.finditer(r"@\w+\s*\{\s*([^,\s]+)\s*,(.*?)(?=\n@|\Z)", open(p, encoding="utf-8", errors="replace").read(), re.S):
            d = re.search(r"doi\s*=\s*[{\"]([^}\"]+)", m.group(2)); u = re.search(r"\burl\s*=\s*[{\"]([^}\"]+)", m.group(2))
            bib[m.group(1)] = ("https://doi.org/" + d.group(1)) if d else (u.group(1) if u else "")


def ref(keys):
    out = []
    for k in keys.split(";"):
        if not k: continue
        out.append(f"[{k}]({bib[k]})" if bib.get(k) else k)
    return ", ".join(out)


L = ["# Benchmark datasets", "",
     f"{len(rows)} datasets from Tables 1(a) and 1(b) of the survey, generated by `scripts/make_tables.py`. Scale: I = images, F = frames, S = scenarios, H = hours.", ""]
for pillar in ("Sense", "Plan", "Act"):
    L += [f"## {pillar}", "", "| Task | Dataset | Year | Region | Scale | Notable property | Source |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        if r["pillar"] == pillar:
            L.append(f"| {r['task']} | {r['dataset']} | {r['year']} | {r['region']} | {r['scale']} | {r['note']} | {ref(r['cite_keys'])} |")
    L.append("")
open(os.path.join(root, "tables", "datasets.md"), "w", encoding="utf-8").write("\n".join(L))

# survey taxonomy with references
t = open(intro_tex, encoding="utf-8").read()
m = re.search(r"\\label\{tab:survey_taxonomy\}(.*?)\\end\{tabularx\}", t, re.S)
srows = []
for line in m.group(1).split("\n"):
    if line.strip().startswith("\\textbf{") and "&" in line and "Research Category" not in line:
        a, b = line.split("&", 1)
        b = b.rstrip().rstrip("\\").rstrip()
        srows.append((clean(a), clean(re.sub(r"~?\\cite\{[^}]*\}", "", b)), ";".join(dict.fromkeys(cites(b)))))
with open(os.path.join(root, "data", "survey_references.csv"), "w", encoding="utf-8", newline="") as f:
    w = csv.writer(f); w.writerow(["category", "focus", "cite_keys"]); w.writerows(srows)
L = ["# Taxonomy of autonomous driving surveys (2016-2025)", "",
     f"{len(srows)} research categories, from Table 2 of the survey.", "",
     "| Category | Focus | Surveys cited |", "|---|---|---|"]
for a, b, k in srows:
    L.append(f"| {a} | {b} | {ref(k)} |")
open(os.path.join(root, "tables", "surveys.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")

# maturity tables
mat = list(csv.DictReader(open(os.path.join(root, "data", "maturity.csv"), encoding="utf-8")))
L = ["# Algorithmic maturity by on-road entropy", "",
     "M1 mature and fielded; M2 proven, not deployed at that complexity; M3 research prototype; M4 absent. E1 to E5 grade the road, from segregated motorway to lane-free negotiated flow.", ""]
for stage in ("Sense", "Plan", "Act"):
    L += [f"## {stage}", "", "| Method family | E1 | E2 | E3 | E4 | E5 | Basis of the hardest grade |", "|---|---|---|---|---|---|---|"]
    for r in mat:
        if r["stage"] == stage:
            L.append(f"| {r['family']} | {r['E1']} | {r['E2']} | {r['E3']} | {r['E4']} | {r['E5']} | {r['basis']} |")
    L.append("")
open(os.path.join(root, "tables", "maturity.md"), "w", encoding="utf-8").write("\n".join(L))
print(len(rows), "datasets;", len(srows), "survey categories;", len(mat), "maturity rows")
